#' @include content.R
#' @include tools-built-in.R
#' @include rounds.R
NULL

#' Convert a conversation into a trajectory-v1 record
#'
#' @description
#' `r lifecycle::badge("experimental")`
#'
#' `contents_trajectory()` serializes a [Chat], [Round], or [Turn] object into
#' a plain R list matching the shape of the letta-ai `trajectory-v1` JSON
#' schema: an ordered list of records describing the `user`, `assistant`,
#' `reasoning`, and `tool` events in a conversation, preceded by a `meta`
#' record.
#'
#' Call `jsonlite::toJSON(x, auto_unbox = TRUE, null = "null")` on the result
#' to obtain the JSON text for the trajectory. `null = "null"` is required so
#' that assistant tool-call records (which carry `content = NULL`) serialize
#' their `content` field as JSON `null`, matching the schema, rather than
#' having it dropped.
#'
#' The `trajectory-v1` schema allows each record to carry a `timestamp`.
#' ellmer does not track per-turn timestamps, except when the provider itself
#' reports one; currently this is only the case for OpenAI's Responses API.
#' When no timestamp is available, the field is omitted rather than
#' synthesized.
#'
#' @examples
#' turns <- list(
#'   UserTurn(list(
#'     ContentText("What's this image?"),
#'     content_image_url("https://placehold.co/200x200")
#'   )),
#'   AssistantTurn("It's a placeholder image.")
#' )
#'
#' lapply(turns, contents_trajectory)
#'
#' @param content A [Chat], [Round], or [Turn] object to convert into a
#'   trajectory-v1 record.
#' @return A plain R list matching the `trajectory-v1` schema. When `content`
#'   is a [Chat], the result is the full ordered list of records (starting
#'   with `meta`); when `content` is a [Round] or a [Turn], the result is the
#'   list of records generated by that round or turn alone.
#' @export
contents_trajectory <- new_generic("contents_trajectory", "content")

method(contents_trajectory, Content) <- function(content) {
  NULL
}

method(contents_trajectory, ContentText) <- function(content) {
  trajectory_fragment("text", text = content@text)
}

method(contents_trajectory, ContentThinking) <- function(content) {
  trajectory_fragment("reasoning", text = content@thinking)
}

method(contents_trajectory, ContentImageRemote) <- function(content) {
  trajectory_fragment("text", text = sprintf("[image: %s]", content@url))
}

method(contents_trajectory, ContentImageInline) <- function(content) {
  trajectory_fragment("text", text = "[inline image]")
}

method(contents_trajectory, ContentPDF) <- function(content) {
  trajectory_fragment("text", text = sprintf("[pdf: %s]", content@filename))
}

method(contents_trajectory, ContentUploaded) <- function(content) {
  trajectory_fragment(
    "text",
    text = sprintf("[uploaded file: %s]", content@uri)
  )
}

method(contents_trajectory, ContentJson) <- function(content) {
  text <- content@string %||% as_json_string(content@data)
  trajectory_fragment("text", text = text)
}

method(contents_trajectory, ContentToolRequest) <- function(content) {
  trajectory_fragment(
    "tool_call",
    id = content@id,
    name = content@name,
    args = as_json_string(content@arguments)
  )
}

method(contents_trajectory, ContentToolResult) <- function(content) {
  id <- if (is.null(content@request)) NULL else content@request@id
  value <- content@value
  text <- if (
    !tool_errored(content) &&
      (S7_inherits(value, Content) ||
        (is.list(value) && all(map_lgl(value, \(x) S7_inherits(x, Content)))))
  ) {
    tool_result_content_string(value)
  } else {
    tool_string(content)
  }
  trajectory_fragment("tool_result", id = id, content = text)
}

method(contents_trajectory, ContentToolRequestSearch) <- function(content) {
  trajectory_fragment(
    "tool_call_search",
    name = "web_search",
    args = as_json_string(list(query = content@query))
  )
}

method(contents_trajectory, ContentToolResponseSearch) <- function(content) {
  trajectory_fragment(
    "tool_result_search",
    content = paste(content@urls, collapse = "\n")
  )
}

method(contents_trajectory, ContentToolRequestFetch) <- function(content) {
  trajectory_fragment(
    "tool_call_fetch",
    name = "web_fetch",
    args = as_json_string(list(url = content@url))
  )
}

method(contents_trajectory, ContentToolResponseFetch) <- function(content) {
  trajectory_fragment("tool_result_fetch", content = content@url)
}

method(contents_trajectory, Turn) <- function(content, turn_index = 1L) {
  fold_trajectory_contents(content, turn_index = turn_index)
}

method(contents_trajectory, SystemTurn) <- function(content, turn_index = 1L) {
  list()
}

method(contents_trajectory, Round) <- function(content) {
  turns <- c(content@input, content@response)
  records <- imap(turns, function(turn, i) {
    contents_trajectory(turn, turn_index = i)
  })
  unlist(records, recursive = FALSE)
}

method(contents_trajectory, new_S3_class("Chat")) <- function(content) {
  meta <- list(role = "meta", source = "ellmer", model = content$get_model())

  turns <- content$get_turns(include_system_prompt = FALSE)
  records <- imap(turns, function(turn, i) {
    contents_trajectory(turn, turn_index = i)
  })

  c(list(meta), unlist(records, recursive = FALSE))
}

# Helpers ----------------------------------------------------------------------

trajectory_fragment <- function(type, ...) {
  list(type = type, ...)
}

as_json_string <- function(x) {
  as.character(jsonlite::toJSON(x, auto_unbox = TRUE))
}

# A tool result's @value can itself be a Content object (or list of them),
# e.g. a screenshot tool returning ContentImageInline. trajectory-v1's
# `tool.content` is a plain string, so images and PDFs are inlined as base64
# data URIs and text content is unwrapped; anything else falls back to its
# usual trajectory placeholder.
tool_result_content_string <- function(value) {
  if (is.list(value)) {
    paste(map_chr(value, tool_result_content_string), collapse = "\n\n")
  } else if (S7_inherits(value, ContentText)) {
    value@text
  } else if (S7_inherits(value, ContentImageInline) && !is.null(value@data)) {
    sprintf("data:%s;base64,%s", value@type, value@data)
  } else if (S7_inherits(value, ContentPDF)) {
    sprintf("data:%s;base64,%s", value@type, value@data)
  } else {
    fragment <- contents_trajectory(value)
    if (is.null(fragment) || is.null(fragment$text)) "" else fragment$text
  }
}

format_iso8601 <- function(epoch) {
  format(
    as.POSIXct(epoch, tz = "UTC", origin = "1970-01-01"),
    "%Y-%m-%dT%H:%M:%SZ"
  )
}

turn_timestamp <- function(turn) {
  if (!S7_inherits(turn, AssistantTurn)) {
    return(NULL)
  }

  created_at <- turn@json$created_at
  if (is.numeric(created_at) && is.finite(created_at)) {
    format_iso8601(created_at)
  } else {
    NULL
  }
}

with_timestamp <- function(record, timestamp) {
  if (is.null(timestamp)) {
    record
  } else {
    c(record, list(timestamp = timestamp))
  }
}

fold_trajectory_contents <- function(turn, turn_index) {
  role <- if (is_user_turn(turn)) "user" else "assistant"
  timestamp <- turn_timestamp(turn)

  # Drop empty ContentText so a provider that emits an empty text chunk
  # alongside tool calls (e.g. Databricks) does not produce a bogus record
  # with content = "", matching the replay/provider handling.
  is_empty_text <- map_lgl(turn@contents, function(x) {
    S7_inherits(x, ContentText) && !nzchar(x@text)
  })
  contents <- turn@contents[!is_empty_text]

  records <- list()
  text_buffer <- character()
  tool_calls <- list()
  search_ids <- character()
  fetch_ids <- character()
  counter <- 0L

  flush_text <- function() {
    if (length(text_buffer) == 0) {
      return()
    }
    text <- paste(text_buffer, collapse = "\n\n")
    text_buffer <<- character()
    if (role == "user") {
      record <- list(role = "user", content = text)
    } else {
      record <- list(role = "assistant", content = text)
    }
    records[[length(records) + 1]] <<- with_timestamp(record, timestamp)
  }

  flush_tool_calls <- function() {
    if (length(tool_calls) == 0) {
      return()
    }
    record <- list(
      role = "assistant",
      content = NULL,
      tool_calls = tool_calls
    )
    tool_calls <<- list()
    records[[length(records) + 1]] <<- with_timestamp(record, timestamp)
  }

  for (item in contents) {
    fragment <- contents_trajectory(item)
    if (is.null(fragment)) {
      next
    }

    type <- fragment$type

    if (type == "text") {
      flush_tool_calls()
      text_buffer[[length(text_buffer) + 1]] <- fragment$text
    } else if (type == "reasoning") {
      flush_text()
      flush_tool_calls()
      record <- list(role = "reasoning", content = fragment$text)
      records[[length(records) + 1]] <- with_timestamp(record, timestamp)
    } else if (type == "tool_call") {
      flush_text()
      tool_calls[[length(tool_calls) + 1]] <- list(
        id = fragment$id,
        name = fragment$name,
        args = fragment$args
      )
    } else if (type == "tool_result") {
      flush_text()
      flush_tool_calls()
      id <- fragment$id
      if (is.null(id)) {
        counter <- counter + 1L
        id <- sprintf("tool_%d_%d", turn_index, counter)
      }
      record <- list(
        role = "tool",
        tool_call_id = id,
        content = fragment$content
      )
      records[[length(records) + 1]] <- with_timestamp(record, timestamp)
    } else if (type == "tool_call_search") {
      flush_text()
      counter <- counter + 1L
      search_id <- sprintf("websearch_%d_%d", turn_index, counter)
      search_ids[[length(search_ids) + 1]] <- search_id
      tool_calls[[length(tool_calls) + 1]] <- list(
        id = search_id,
        name = fragment$name,
        args = fragment$args
      )
    } else if (type == "tool_result_search") {
      flush_text()
      flush_tool_calls()
      if (length(search_ids) > 0) {
        id <- search_ids[[1]]
        search_ids <- search_ids[-1]
      } else {
        counter <- counter + 1L
        id <- sprintf("websearch_%d_%d", turn_index, counter)
      }
      record <- list(
        role = "tool",
        tool_call_id = id,
        content = fragment$content
      )
      records[[length(records) + 1]] <- with_timestamp(record, timestamp)
    } else if (type == "tool_call_fetch") {
      flush_text()
      counter <- counter + 1L
      fetch_id <- sprintf("webfetch_%d_%d", turn_index, counter)
      fetch_ids[[length(fetch_ids) + 1]] <- fetch_id
      tool_calls[[length(tool_calls) + 1]] <- list(
        id = fetch_id,
        name = fragment$name,
        args = fragment$args
      )
    } else if (type == "tool_result_fetch") {
      flush_text()
      flush_tool_calls()
      if (length(fetch_ids) > 0) {
        id <- fetch_ids[[1]]
        fetch_ids <- fetch_ids[-1]
      } else {
        counter <- counter + 1L
        id <- sprintf("webfetch_%d_%d", turn_index, counter)
      }
      record <- list(
        role = "tool",
        tool_call_id = id,
        content = fragment$content
      )
      records[[length(records) + 1]] <- with_timestamp(record, timestamp)
    }
  }

  flush_text()
  flush_tool_calls()

  records
}
